// An npm package installed from a directory (a `file:` one, which pnpm and yarn copy into node_modules) is
// no registry's package of its name: its record is tagged npm:directory and names the directory, from
// the bundle's root, in place of an integrity. Each layout here is written by hand as the package
// manager writes one, or laid out by deptree from a lockfile.

const here = dirname(fileURLToPath(import.meta.url))
const SRI = `sha512-${'A'.repeat(86)}==`
const STORE = 'node_modules/.pnpm/lib@file+vendor+lib/node_modules/lib'
const FROM_LIB = { ecosystem: NPM_DIRECTORY, directory: 'vendor/lib' }
const writeJson = (file, value) => writeFileSync(file, JSON.stringify(value))
const readJson = (file) => JSON.parse(readFileSync(file, 'utf8'))
const recordsOf = (dir, file) => JSON.parse(brotliDecompressSync(readFileSync(join(dir, file))).toString('utf8')).modules
// A record as written, its files by name alone.
const shapeOf = ({ files, ...record }) => ({ ...record, files: Object.keys(files).toSorted() })
const stasis = (dir, ...args) => spawnSync(process.execPath, [join(here, '..', 'stasis', 'bin', 'stasis.js'), ...args], { cwd: dir, encoding: 'utf8', env: { ...process.env, EXODUS_STASIS_LOCK: '' } })

const YARN_LOCK = '# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n\n'
const pnpmLock = (directory = 'vendor/lib') => ["lockfileVersion: '9.0'", '', 'settings:', '  autoInstallPeers: true', '  excludeLinksFromLockfile: false', '', 'importers:', '', '  .:', '    dependencies:',
  '      lib:', `        specifier: file:./${directory}`, `        version: file:${directory}`, '', 'packages:', '', `  lib@file:${directory}:`, `    resolution: {directory: ${directory}, type: directory}`, '',
  'snapshots:', '', `  lib@file:${directory}: {}`, ''].join('\n')

// The project in `dir` requiring lib, and lib in vendor/lib and in its copy at `copy`, each its index.js
// as given (the copy's, the source's by default).
function writeProject(dir, copy, { source = 'module.exports = 1\n', copied = source } = {}) {
  writeJson(join(dir, 'package.json'), { name: 'app', version: '1.0.0', dependencies: { lib: 'file:./vendor/lib' } })
  writeFileSync(join(dir, 'index.js'), "require('lib')\n")
  for (const [at, index] of [['vendor/lib', source], [copy, copied]]) {
    mkdirSync(join(dir, at), { recursive: true })
    writeJson(join(dir, at, 'package.json'), { name: 'lib', version: '1.0.0' })
    writeFileSync(join(dir, at, 'index.js'), index)
  }
}

// As pnpm isolates it (copied into its store, linked from node_modules/lib) or hoists it, its lockfile and the copy
// pnpm keeps of it.
function pnpmProject(dir, files, { linker = 'isolated' } = {}) {
  const isolated = linker === 'isolated'
  writeProject(dir, isolated ? STORE : 'node_modules/lib', files)
  if (isolated) symlinkSync('.pnpm/lib@file+vendor+lib/node_modules/lib', join(dir, 'node_modules', 'lib'))
  else mkdirSync(join(dir, 'node_modules', '.pnpm'))
  writeFileSync(join(dir, 'node_modules', '.modules.yaml'), `nodeLinker: ${linker}\npackageManager: pnpm@10.33.4\n`)
  writeFileSync(join(dir, 'pnpm-lock.yaml'), pnpmLock())
  writeFileSync(join(dir, 'node_modules', '.pnpm', 'lock.yaml'), pnpmLock())
}

// As yarn 1 hoists it, yarn.lock locking it by its spec alone and .yarn-integrity resolving it at ''.
function yarnProject(dir) {
  writeProject(dir, 'node_modules/lib')
  writeFileSync(join(dir, 'yarn.lock'), `${YARN_LOCK}"lib@file:./vendor/lib":\n  version "1.0.0"\n`)
  writeJson(join(dir, 'node_modules', '.yarn-integrity'), { flags: [], linkedModules: [], topLevelPatterns: ['lib@file:./vendor/lib'], lockfileEntries: { 'lib@file:./vendor/lib': '' }, files: [], artifacts: {} })
}

const BUILDS = [['state', {}], ['resolver', { mainFields: ['main'] }]]
const build = (dir, options = {}) => bundleCommand({ cwd: dir, entries: ['index.js'], output: 'out.br', ...options })

test('an npm:directory record names its directory, carries no integrity or patch, and is no first-party one', (t) => {
  const json = (record, at = STORE) => JSON.stringify({ version: 1, config: { scope: 'full' }, entries: ['index.js'], formats: {}, imports: {}, sources: { '.': { name: 'app', version: '1.0.0', files: { 'index.js': '' } } },
    modules: { [at]: { name: 'lib', version: '1.0.0', ...record, files: { 'index.js': 'module.exports = 1\n' } } } })
  const parsed = (record) => shapeOf(Bundle.parse(json(record)).modules.get(STORE))
  for (const directory of ['vendor/lib', '.', '..', '../..', '../shared/lib']) t.assert.equal(parsed({ ecosystem: NPM_DIRECTORY, directory }).directory, directory, directory)
  for (const directory of ['', '/vendor/lib', 'vendor/lib/', 'vendor/../lib', './vendor/lib', 'vendor\\lib', 1]) {
    t.assert.throws(() => parsed({ ecosystem: NPM_DIRECTORY, directory }), /invalid bundle module '.+' directory:/u, JSON.stringify(directory))
  }
  t.assert.throws(() => parsed({ ecosystem: NPM_DIRECTORY }), /is tagged npm:directory, and records no directory$/u)
  t.assert.throws(() => parsed({ ecosystem: 'npm', directory: 'vendor/lib' }), /is no npm:directory dependency's bucket, and carries no directory$/u)
  t.assert.throws(() => parsed({ directory: 'vendor/lib' }), /is no npm:directory dependency's bucket, and carries no directory$/u, 'untagged, as npm\'s')
  t.assert.throws(() => parsed({ ...FROM_LIB, integrity: SRI }), /was installed from a directory, no archive, and carries no integrity$/u)
  t.assert.throws(() => parsed({ ...FROM_LIB, patch: { integrity: `sha256-${'A'.repeat(43)}=` } }), /is no npm dependency's bucket, and carries no patch$/u)
  const own = JSON.parse(json(FROM_LIB))
  own.sources.lib = { name: 'lib', ecosystem: NPM_DIRECTORY, files: {} }
  t.assert.throws(() => Bundle.parse(JSON.stringify(own)), /'lib' is no node_modules bucket, though tagged npm:directory, and records no directory$/u)

  // A lockfile records it too, so that one can be audited alone.
  const lock = Lockfile.parse(JSON.stringify({ version: 0, config: { scope: 'node_modules' }, imports: {}, formats: {}, modules: { [STORE]: { name: 'lib', version: '1.0.0', ...FROM_LIB, files: { 'index.js': SRI } } } }))
  t.assert.deepStrictEqual(JSON.parse(lock.serialize()).modules[STORE], { name: 'lib', version: '1.0.0', ...FROM_LIB, files: { 'index.js': SRI } })

  // The tag goes with the value, as a record gains one of its install, or loses one taken apart.
  const npm = moduleInfo({ name: 'lib', version: '1.0.0', ecosystem: 'npm', files: {} })
  t.assert.deepStrictEqual(Object.keys(moduleInfo({ ...npm, directory: 'vendor/lib' })), ['name', 'version', 'ecosystem', 'directory', 'files'])
  t.assert.equal(moduleInfo({ ...npm, directory: 'vendor/lib' }).ecosystem, NPM_DIRECTORY)
  t.assert.equal(moduleInfo({ ...npm, ...FROM_LIB, directory: undefined }).ecosystem, 'npm')
})

test('a merge takes an npm record attesting nothing, an older stasis\'s, as npm:directory\'s, but no other npm record', (t) => {
  const at = (record, files = ['index.js']) => new Map([[STORE, moduleInfo({ name: 'lib', version: '1.0.0', ...record, files: Object.fromEntries(files.map((file) => [file, 'x'])) })]])
  for (const [a, b] of [[at({ ecosystem: 'npm' }), at(FROM_LIB)], [at(FROM_LIB), at({ ecosystem: 'npm' })]]) {
    t.assert.deepStrictEqual(shapeOf(mergeModuleMaps(a, b, 'merge').get(STORE)), { name: 'lib', version: '1.0.0', ...FROM_LIB, files: ['index.js'] })
  }
  // One of an archive's integrity was installed from no directory.
  t.assert.throws(() => mergeModuleMaps(at({ ecosystem: 'npm', integrity: SRI }), at(FROM_LIB), 'merge'), /^Error: merge: module '.+' directory mismatch \(none vs "vendor\/lib"\)$/u)
  t.assert.throws(() => mergeModuleMaps(at(FROM_LIB), at({ ecosystem: 'npm', integrity: SRI }), 'merge'), /^Error: merge: module '.+' directory mismatch \("vendor\/lib" vs none\)$/u)
  t.assert.throws(() => mergeModuleMaps(at({ ecosystem: 'npm', patch: { integrity: `sha256-${'A'.repeat(43)}=` } }), at(FROM_LIB), 'merge'), /directory mismatch \(none vs "vendor\/lib"\)$/u, 'nor one patched')
  t.assert.throws(() => mergeModuleMaps(at({ ecosystem: 'cargo' }), at(FROM_LIB), 'merge'), /ecosystem mismatch \('cargo' vs 'npm:directory'\)$/u)
  t.assert.throws(() => mergeModuleMaps(at(FROM_LIB), at({ ...FROM_LIB, directory: 'vendor/other' }), 'merge'), /directory mismatch \("vendor\/lib" vs "vendor\/other"\)$/u)
  t.assert.throws(() => mergeModuleMaps(at({ ecosystem: 'npm' }, ['other.js']), at(FROM_LIB), 'merge'), /directory is recorded of one side's files, not of '.+\/other\.js' the other adds$/u)
})

test('a disk build records a package pnpm or yarn 1 installs from a directory by it, from the bundle root, and holds it to the lockfile beside', withTmp(async (t, tmp) => {
  for (const [manager, write, copy] of [['pnpm', pnpmProject, STORE], ['yarn', yarnProject, 'node_modules/lib']]) {
    const dir = join(tmp, manager)
    mkdirSync(dir)
    write(dir)
    for (const [label, options] of BUILDS) {
      await build(dir, { ...options, output: `${label}.br` }) // eslint-disable-line no-await-in-loop -- one build at a time
      const { files: _files, ...record } = recordsOf(dir, `${label}.br`)[copy]
      t.assert.deepStrictEqual(record, { name: 'lib', version: '1.0.0', ...FROM_LIB }, `${manager} ${label}`)
    }
  }
  // Where pnpm hoists, held by its name: pnpm-lock.yaml installing it from another directory than pnpm did.
  const hoisted = join(tmp, 'hoisted')
  mkdirSync(hoisted)
  pnpmProject(hoisted, {}, { linker: 'hoisted' })
  await build(hoisted)
  t.assert.equal(recordsOf(hoisted, 'out.br')['node_modules/lib'].directory, 'vendor/lib')
  writeFileSync(join(hoisted, 'pnpm-lock.yaml'), pnpmLock('vendor/other'))
  await t.assert.rejects(build(hoisted), /pnpm-lock\.yaml doesn't lock node_modules\/lib as installed \(installed from .+\/vendor\/lib; it locks .+\/vendor\/other\): install from it again$/u)
}))

test('a disk build holds a copy pnpm installs from a directory to that directory where it is there, as pnpm copies a bin', withTmp(async (t, tmp) => {
  const at = (name, files) => {
    const dir = join(tmp, name)
    mkdirSync(dir)
    pnpmProject(dir, files)
    return dir
  }
  await t.assert.rejects(build(at('edited', { copied: 'module.exports = 2\n' })), { message: `${STORE}/index.js is not vendor/lib/index.js, which it was installed from: install from it again` })
  const gone = at('gone', {})
  rmSync(join(gone, 'vendor', 'lib', 'index.js'))
  await t.assert.rejects(build(gone), /index\.js was installed from vendor\/lib\/index\.js, which is gone: install from it again$/u)
  const image = at('image', { source: 'module.exports = 3\n' })
  rmSync(join(image, 'vendor'), { recursive: true })
  await build(image)
  t.assert.equal(recordsOf(image, 'out.br')[STORE].directory, 'vendor/lib', 'with no source there (node_modules alone copied into an image), nothing tells')
  // pnpm before 12 makes a bin's CRLF `#!` line LF in its copy, and that alone.
  await build(at('crlf', { source: '#!/usr/bin/env node\r\nmodule.exports = 1\r\n', copied: '#!/usr/bin/env node\nmodule.exports = 1\r\n' }))
  await t.assert.rejects(build(at('crlf-more', { source: '#!/usr/bin/env node\r\nmodule.exports = 1\r\n', copied: '#!/usr/bin/env node\nmodule.exports = 1\n' })), /is not vendor\/lib\/index\.js/u)
}))

test('stasis run records a package installed from a directory as one, and a frozen run takes a lockfile of an older stasis recording it npm\'s', withTmp((t, dir) => {
  pnpmProject(dir)
  const replaced = stasis(dir, 'run', '--lock=replace', 'index.js')
  t.assert.equal(replaced.status, 0, replaced.stderr)
  const lockfile = join(dir, 'stasis.lock.json')
  t.assert.deepStrictEqual(shapeOf(readJson(lockfile).modules[STORE]), { name: 'lib', version: '1.0.0', ...FROM_LIB, files: ['index.js'] })
  t.assert.equal(stasis(dir, 'run', '--lock=frozen', 'index.js').status, 0)
  const older = readJson(lockfile)
  older.modules[STORE].ecosystem = 'npm'
  delete older.modules[STORE].directory
  writeJson(lockfile, older)
  const frozen = stasis(dir, 'run', '--lock=frozen', 'index.js')
  t.assert.equal(frozen.status, 0, frozen.stderr)
  writeFileSync(join(dir, STORE, 'index.js'), 'module.exports = 2\n')
  const stale = stasis(dir, 'run', '--lock=replace', 'index.js')
  t.assert.notEqual(stale.status, 0)
  t.assert.match(stale.stderr, /index\.js is not vendor\/lib\/index\.js, which it was installed from: install from it again/u)
}))

test('stasis bundle --add takes a bundle of an older stasis, recording a package installed from a directory as npm\'s, to npm:directory', withTmp(async (t, dir) => {
  pnpmProject(dir)
  await build(dir)
  const bundle = JSON.parse(brotliDecompressSync(readFileSync(join(dir, 'out.br'))))
  bundle.modules[STORE].ecosystem = 'npm'
  delete bundle.modules[STORE].directory
  writeFileSync(join(dir, 'out.br'), brotliCompressSync(JSON.stringify(bundle)))
  await build(dir, { add: true })
  t.assert.deepStrictEqual(shapeOf(recordsOf(dir, 'out.br')[STORE]), { name: 'lib', version: '1.0.0', ...FROM_LIB, files: ['index.js'] })
}))

const vfsOf = (files) => {
  const vfs = new Vfs()
  for (const [rel, text] of Object.entries(files)) {
    vfs.mkdir(posix.dirname(`/${rel}`), { recursive: true })
    vfs.writeFile(`/${rel}`, typeof text === 'string' ? text : `${JSON.stringify(text)}\n`)
  }
  return vfs
}

test('a build from a lockfile alone records a package deptree copies from a directory by it', async (t) => {
  const pnpm = await buildVfsBundle({ packageManager: 'pnpm', entries: ['index.js'], vfs: vfsOf({
    'package.json': { name: 'p', version: '1.0.0', dependencies: { lib: '^1.0.0' }, pnpm: { overrides: { lib: 'file:./vendor/lib' } } },
    'pnpm-lock.yaml': pnpmLock().replace('importers:', 'overrides:\n  lib: file:./vendor/lib\n\nimporters:').replace('specifier: file:./vendor/lib', 'specifier: file:vendor/lib'),
    'vendor/lib/package.json': { name: 'lib', version: '1.0.0', main: 'index.js' },
    'vendor/lib/index.js': 'module.exports = 1\n',
    'index.js': "require('lib')\n",
  }) })
  t.assert.deepStrictEqual(shapeOf(pnpm.bundle.modules.get(STORE)), { name: 'lib', version: '1.0.0', ...FROM_LIB, files: ['index.js'] })
  t.assert.deepStrictEqual(pnpm.accounts.get(STORE), { directory: 'vendor/lib', integrity: undefined, patch: undefined })
  const yarn = await buildVfsBundle({ packageManager: 'yarn1', entries: ['index.js'], vfs: vfsOf({
    'package.json': { name: 'p', version: '1.0.0', dependencies: { lib: 'file:vendor/lib' } },
    'yarn.lock': `${YARN_LOCK}"lib@file:vendor/lib":\n  version "1.0.0"\n`,
    'vendor/lib/package.json': { name: 'lib', version: '1.0.0', main: 'index.js' },
    'vendor/lib/index.js': 'module.exports = 1\n',
    'index.js': "require('lib')\n",
  }) })
  t.assert.deepStrictEqual(shapeOf(yarn.bundle.modules.get('node_modules/lib')), { name: 'lib', version: '1.0.0', ...FROM_LIB, files: ['index.js'] })
})

const artifactOf = (modules) => new Bundle({ config: { scope: 'node_modules' }, modules: new Map(Object.entries(modules)), formats: new Map(), imports: new Map() })

test('sbom lists an npm:directory package with no purl, which names the registry\'s package', (t) => {
  const components = collectComponents([artifactOf({
    [STORE]: { name: 'lib', version: '1.0.0', ...FROM_LIB, files: { 'index.js': '' } },
    'node_modules/.pnpm/@org+lib@file+vendor+org/node_modules/@org/lib': { name: '@org/lib', version: '2.0.0', ecosystem: NPM_DIRECTORY, directory: 'vendor/org', files: { 'index.js': '' } },
    'node_modules/reg': { name: 'reg', version: '1.0.0', ecosystem: 'npm', integrity: SRI, files: { 'index.js': '' } },
  })])
  t.assert.deepStrictEqual(components.map(({ name, ecosystem, purl, scope }) => [name, ecosystem, purl, scope]), [
    ['@org/lib', NPM_DIRECTORY, null, 'dependency'],
    ['lib', NPM_DIRECTORY, null, 'dependency'],
    ['reg', 'npm', 'pkg:npm/reg@1.0.0', 'dependency'],
  ])
})

test('audit asks no database of an npm:directory package, whose name may be private', withTmp(async (t, dir) => {
  const file = join(dir, 'stasis.code.br')
  writeFileSync(file, brotliCompressSync(artifactOf({
    [STORE]: { name: 'lib', version: '1.0.0', ...FROM_LIB, files: { 'index.js': 'module.exports = 1\n' } },
    'node_modules/reg': { name: 'reg', version: '1.0.0', ecosystem: 'npm', integrity: SRI, files: { 'index.js': 'module.exports = 2\n' } },
  }).serialize()))
  const original = globalThis.fetch
  const asked = []
  globalThis.fetch = async (url, opts) => {
    asked.push(JSON.parse(opts.body))
    return new Response('{}', { status: 200, headers: { 'content-type': 'application/json' } })
  }
  try {
    const report = await audit([file])
    t.assert.deepStrictEqual(asked, [{ reg: ['1.0.0'] }])
    t.assert.deepStrictEqual(report.skipped.map(({ ecosystem, name, because }) => [ecosystem, name, because]), [[NPM_DIRECTORY, 'lib', 'an npm package installed from a directory, not the registry']])
  } finally {
    globalThis.fetch = original
  }
}))

test('stasis diff tells a record taking the directory its package was installed from', (t) => {
  const of = (record) => ({ artifact: artifactOf({ [STORE]: { name: 'lib', version: '1.0.0', ...record, files: { 'index.js': 'x\n' } } }), kind: 'bundle' })
  const diff = diffArtifacts(of({ ecosystem: 'npm' }), of(FROM_LIB), { hash: (x) => x })
  t.assert.deepStrictEqual(diff.modules.changed, [{ dir: STORE, name: 'lib', directoryChange: { from: undefined, to: 'vendor/lib' } }])
  t.assert.ok(formatDiffStat(diff).includes(`${STORE}  lib directory none -> vendor/lib`), formatDiffStat(diff))
})
